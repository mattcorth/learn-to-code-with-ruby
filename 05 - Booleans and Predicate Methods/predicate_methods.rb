=begin
  A predicate method, AKA a boolean method
  is an object method that returns a boolean value
  
  Community convention is for a predicate method name to end with a '?'
=end
puts 10.odd?
puts 11.odd?

puts 1.even?
puts 2.even?

puts 10.positive?
puts 10.negative?

puts -8.positive?
puts -8.negative?